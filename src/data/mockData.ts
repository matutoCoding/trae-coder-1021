export const generateTemperatureHistory = (base: number, days: number = 7) => {
  const data = []
  const now = new Date()
  for (let i = days - 1; i >= 0; i--) {
    const date = new Date(now)
    date.setDate(date.getDate() - i)
    for (let h = 0; h < 24; h += 4) {
      data.push({
        time: `${date.getMonth() + 1}/${date.getDate()} ${h.toString().padStart(2, '0')}:00`,
        温度: base + (Math.random() - 0.5) * 8,
        湿度: 50 + (Math.random() - 0.5) * 30,
      })
    }
  }
  return data
}
